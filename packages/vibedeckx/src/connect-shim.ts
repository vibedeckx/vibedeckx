import fs from "node:fs";
import path from "node:path";
import { writeFileAtomic } from "./utils/atomic-file.js";

/**
 * A stable `vibedeckx` command for day-to-day management after
 * `npx vibedeckx@<version> connect install`. It execs the installed
 * runtime's launcher, so it never touches npm or the network, and it always
 * runs the same version as the worker it manages (it follows `current`).
 *
 * Only for the default data-dir (one command per machine), and never over a
 * `vibedeckx` we did not write.
 */

export const SHIM_MARKER = "# vibedeckx-connect-shim";

export function shimPath(home: string, platform: NodeJS.Platform = process.platform): string {
  return path.join(home, ".local", "bin", platform === "win32" ? "vibedeckx.cmd" : "vibedeckx");
}

function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

export function renderShim(launcher: string, platform: NodeJS.Platform = process.platform): string {
  if (platform === "win32") {
    // The last command's exit code is the batch file's; `%` must be doubled.
    return [
      "@echo off",
      `rem ${SHIM_MARKER}`,
      "rem Generated by `vibedeckx connect install`; removed by `vibedeckx connect uninstall`.",
      `"${launcher.replace(/%/g, "%%")}" %*`,
      "",
    ].join("\r\n");
  }
  return `#!/bin/sh
${SHIM_MARKER}
# Generated by \`vibedeckx connect install\`; removed by \`vibedeckx connect uninstall\`.
exec ${shQuote(launcher)} "$@"
`;
}

function isOurs(filePath: string): boolean {
  try {
    return fs.readFileSync(filePath, "utf8").includes(SHIM_MARKER);
  } catch {
    return false;
  }
}

export type ShimOutcome =
  | { kind: "installed"; path: string; onPath: boolean; shadowedBy?: string }
  | { kind: "foreign"; path: string }
  | { kind: "non-default" };

export interface ShimOptions {
  dataDir: string;
  launcher: string;
  home: string;
  pathEnv: string;
}

function firstOnPath(command: string, pathEnv: string): string | undefined {
  const extensions =
    process.platform === "win32" ? (process.env.PATHEXT ?? ".COM;.EXE;.BAT;.CMD").split(";").filter(Boolean) : [""];
  for (const directory of pathEnv.split(path.delimiter)) {
    if (!directory) continue;
    for (const extension of extensions) {
      const candidate = path.join(directory, command + extension);
      try {
        fs.accessSync(candidate, fs.constants.X_OK);
        return candidate;
      } catch {
        // keep looking
      }
    }
  }
  return undefined;
}

function onPath(directory: string, pathEnv: string): boolean {
  const normalize = (value: string): string =>
    process.platform === "win32" ? path.resolve(value).toLowerCase() : value;
  return pathEnv.split(path.delimiter).some((entry) => entry && normalize(entry) === normalize(directory));
}

function isDefaultDataDir(dataDir: string, home: string): boolean {
  return path.resolve(dataDir) === path.resolve(home, ".vibedeckx");
}

export function installShim(options: ShimOptions): ShimOutcome {
  if (!isDefaultDataDir(options.dataDir, options.home)) return { kind: "non-default" };
  const target = shimPath(options.home);
  if (fs.existsSync(target) && !isOurs(target)) return { kind: "foreign", path: target };

  writeFileAtomic(target, renderShim(options.launcher), { mode: 0o755 });
  const binDir = path.dirname(target);
  const isOnPath = onPath(binDir, options.pathEnv);
  const first = firstOnPath("vibedeckx", options.pathEnv);
  return {
    kind: "installed",
    path: target,
    onPath: isOnPath,
    shadowedBy: isOnPath && first && path.resolve(first) !== path.resolve(target) ? first : undefined,
  };
}

/** Remove the shim if we wrote it. Returns whether something was removed. */
export function removeShim(options: { dataDir: string; home: string }): boolean {
  if (!isDefaultDataDir(options.dataDir, options.home)) return false;
  const target = shimPath(options.home);
  if (!isOurs(target)) return false;
  fs.rmSync(target, { force: true });
  return true;
}

export function describeShim(outcome: ShimOutcome, dataDir: string, launcher: string): string[] {
  switch (outcome.kind) {
    case "installed": {
      const lines = [`Manage it with \`vibedeckx connect status|stop|start|restart\` (${outcome.path}).`];
      if (!outcome.onPath && process.platform === "win32") {
        lines.push(
          `${path.dirname(outcome.path)} is not on your PATH; add it for your user (PowerShell), then open a new terminal:`,
          `  [Environment]::SetEnvironmentVariable("Path", [Environment]::GetEnvironmentVariable("Path", "User") + ";${path.dirname(outcome.path)}", "User")`,
        );
      } else if (!outcome.onPath) {
        lines.push(
          `${path.dirname(outcome.path)} is not on your PATH; add it to your shell profile:`,
          `  export PATH="${path.dirname(outcome.path)}:$PATH"`,
        );
      } else if (outcome.shadowedBy) {
        lines.push(`Note: ${outcome.shadowedBy} comes first on your PATH and will run instead.`);
      }
      return lines;
    }
    case "foreign":
      return [
        `Did not create ${outcome.path}: another \`vibedeckx\` is already there.`,
        `Manage this worker with: ${launcher} connect status`,
      ];
    case "non-default":
      return [`Manage this worker with: ${launcher} connect status --data-dir ${dataDir}`];
  }
}
